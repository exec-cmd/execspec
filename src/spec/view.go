package spec

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const RoadmapFile = "ROADMAP.md"

var htmlComment = regexp.MustCompile(`(?s)<!--.*?-->`)

// parents maps an item number to the item that includes it, when both are on
// the same side of the archive.
func parents(items []*Item) map[int]*Item {
	p := map[int]*Item{}
	for _, it := range items {
		for _, n := range it.Includes {
			if c := byNum(items, n); c != nil && c.Archived == it.Archived {
				if _, ok := p[n]; !ok {
					p[n] = it
				}
			}
		}
	}
	return p
}

func roadmapLine(it *Item) string {
	note := it.Status
	if it.Started() {
		note += fmt.Sprintf(", %d/%d tasks", it.Done, it.Total)
	}
	if len(it.Markers) > 0 {
		note += fmt.Sprintf(", %d questions", len(it.Markers))
	}
	return fmt.Sprintf("%s %s %s (%s)", it.ID(), it.Type.Name, it.Title, note)
}

// Roadmap renders the project's plans and history from its items.
func Roadmap(items []*Item) string {
	par := parents(items)
	children := func(it *Item, indent string, line func(*Item) string) string {
		var b strings.Builder
		for _, n := range it.Includes {
			if c := byNum(items, n); c != nil && par[n] == it {
				fmt.Fprintf(&b, "%s- %s\n", indent, line(c))
			}
		}
		return b.String()
	}

	var now, next, history []*Item
	for _, it := range items {
		switch {
		case par[it.Num] != nil:
		case it.Archived:
			history = append(history, it)
		case it.Started():
			now = append(now, it)
		default:
			next = append(next, it)
		}
	}
	sort.SliceStable(history, func(i, j int) bool {
		if history[i].Date != history[j].Date {
			return history[i].Date > history[j].Date
		}
		return history[i].Num > history[j].Num
	})

	var b strings.Builder
	b.WriteString("# Roadmap\n\nGenerated by xspec; do not edit.\n")
	section := func(title string, list []*Item, line func(*Item) string) {
		fmt.Fprintf(&b, "\n## %s\n\n", title)
		if len(list) == 0 {
			b.WriteString("Nothing.\n")
		}
		for _, it := range list {
			fmt.Fprintf(&b, "- %s\n%s", line(it), children(it, "  ", line))
		}
	}
	section("Now", now, roadmapLine)
	section("Next", next, roadmapLine)
	section("History", history, func(it *Item) string {
		s := fmt.Sprintf("%s %s %s", it.ID(), it.Type.Name, it.Title)
		if par[it.Num] == nil {
			s = strings.TrimSpace(it.Date+" "+s) + strings.TrimSuffix(" ("+it.Change+")", " ()")
		}
		return s
	})
	return b.String()
}

// WriteRoadmap rewrites spec/ROADMAP.md.
func WriteRoadmap(root string) error {
	items, err := Scan(root)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, Dir, RoadmapFile), []byte(Roadmap(items)), 0o644)
}

// Next tells what to do now, first match wins: a task of the lowest item in
// progress, closing a finished item, answering questions, then the first task
// of an item not yet started.
func Next(items []*Item) string {
	var active []*Item
	for _, it := range items {
		if !it.Archived {
			active = append(active, it)
		}
	}
	task := func(it *Item) string {
		for _, line := range it.Lines {
			if m := boxRe.FindStringSubmatch(line); m != nil && m[1] == " " && !includeRe.MatchString(line) {
				return fmt.Sprintf("work on %s %s: %s", it.ID(), it.Title, strings.TrimSpace(line[len(m[0]):]))
			}
		}
		return ""
	}
	for _, it := range active {
		if it.Started() {
			if s := task(it); s != "" {
				return s
			}
		}
	}
	par := parents(items)
	for _, it := range active {
		if it.Total > 0 && it.Done == it.Total && par[it.Num] == nil {
			return fmt.Sprintf("close %s %s: xspec done %s", it.ID(), it.Title, it.ID())
		}
	}
	for _, it := range active {
		if len(it.Markers) > 0 {
			return fmt.Sprintf("answer %d questions in %s %s: xspec questions", len(it.Markers), it.ID(), it.Title)
		}
	}
	for _, it := range active {
		if s := task(it); s != "" {
			return s
		}
	}
	return "nothing to do"
}

// Questions lists every open marker in active items, grouped by item.
func Questions(root string, items []*Item) string {
	var b strings.Builder
	for _, it := range items {
		if it.Archived || len(it.Markers) == 0 {
			continue
		}
		fmt.Fprintf(&b, "%s %s %s\n", it.ID(), it.Type.Name, it.Title)
		for _, m := range it.Markers {
			fmt.Fprintf(&b, "  %s:%d  %s\n", short(root, it.File), m.Line, m.Text)
		}
	}
	return b.String()
}

// Context prints the brief for one item: the item, what it includes, the
// SPEC.md's Principles, Ask first and Stack sections, and the glossary.
func Context(root, ref string) (string, error) {
	items, err := Scan(root)
	if err != nil {
		return "", err
	}
	it, err := Find(items, ref)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	part := func(path, body string) {
		if strings.TrimSpace(body) != "" {
			fmt.Fprintf(&b, "=== %s ===\n%s\n\n", short(root, path), strings.TrimSpace(body))
		}
	}
	file := func(path string) {
		data, _ := os.ReadFile(path)
		part(path, string(data))
	}

	g := []*Item{it}
	for _, n := range it.Includes {
		if c := byNum(items, n); c != nil {
			g = append(g, c)
		}
	}
	for _, x := range g {
		file(x.File)
		if x.File != x.Path {
			file(filepath.Join(x.Path, "design.md"))
		}
	}

	specMD := filepath.Join(root, Dir, "SPEC.md")
	data, _ := os.ReadFile(specMD)
	for _, name := range []string{"Principles", "Ask first", "Stack"} {
		part(specMD+" § "+name, htmlComment.ReplaceAllString(section(string(data), name), ""))
	}
	file(filepath.Join(root, Dir, "notes", "glossary.md"))
	return b.String(), nil
}

// section returns the body under a "## name" heading, up to the next "## ".
func section(doc, name string) string {
	var out []string
	in := false
	for _, line := range strings.Split(doc, "\n") {
		if strings.HasPrefix(line, "## ") {
			in = strings.TrimSpace(line[3:]) == name
			continue
		}
		if in {
			out = append(out, line)
		}
	}
	return strings.Join(out, "\n")
}
